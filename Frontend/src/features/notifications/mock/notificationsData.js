export const getInitialNotifications = () => {
  const stored = localStorage.getItem("elexoplus_notifications");
  if (stored) {
    try {
      return JSON.parse(stored);
    } catch {
      return [...NOTIFICATIONS_DATA];
    }
  }
  return [...NOTIFICATIONS_DATA];
};
